#!/usr/bin/env node
// Regenerates src/setup/catalog-spec.data.ts from the PuppyGraph catalog form
// definition, the same file PuppyGraph AI's get_catalog_connection_spec reads:
//
//   node scripts/update-catalog-spec.mjs <puppygraph checkout>/frontend/control/chat/catalogform/definition.json
//
// Only what an agent needs to fill the form is kept.
import fs from "node:fs";

const [source] = process.argv.slice(2);
if (!source) {
  console.error("usage: update-catalog-spec.mjs <path to catalogform/definition.json>");
  process.exit(1);
}
const definition = JSON.parse(fs.readFileSync(source, "utf8"));
const keep = ["name", "type", "label", "defaultValue", "required", "requiredIf", "opts", "sensitive", "tooltip", "placeholder"];
const spec = {
  alwaysActiveFields: definition.alwaysActiveFields,
  jdbcCommonFields: definition.jdbcCommonFields,
  fieldDeps: definition.fieldDeps,
  allFields: definition.allFields.map((field) =>
    Object.fromEntries(keep.filter((key) => key in field).map((key) => [key, field[key]])),
  ),
};
const out = new URL("../src/setup/catalog-spec.data.ts", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/update-catalog-spec.mjs from PuppyGraph's catalog form
// definition (frontend/control/chat/catalogform/definition.json). Do not edit.
import type { CatalogForm } from "./catalog-spec.js";

export const CATALOG_FORM: CatalogForm = ${JSON.stringify(spec, null, 2)};
`,
);
console.log(`wrote ${out.pathname}: ${spec.allFields.length} fields, ${spec.fieldDeps.length} dependencies`);
